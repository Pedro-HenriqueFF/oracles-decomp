#!/usr/bin/env python3
"""Write src/mods/treasures.c: how many subids each treasure index has in each game's
treasureObjectData, so oracles.swap_treasure refuses a pair the engine would read another
treasure's bytes for.

usage: tools/gen_treasures.py [DISASM_DIR] [OUT]
"""
import re, sys

disasm = sys.argv[1] if len(sys.argv) > 1 else 'ref/oracles-disasm'
out = sys.argv[2] if len(sys.argv) > 2 else 'src/mods/treasures.c'


def counts(game):
    top, tables, label, in_top = [], {}, None, False
    for line in open(f'{disasm}/data/{game}/treasureObjectData.s'):
        s = line.split(';')[0].strip()
        if s == 'treasureObjectData:':
            in_top = True
            continue
        m = re.match(r'(treasureObjectData\w+):$', s)
        if m:
            in_top, label = False, m.group(1)
            tables[label] = 0
        elif in_top and 'm_TreasureSubid' in s:
            top.append(1)
        elif in_top and 'm_TreasurePointer' in s:
            top.append(s.split()[-1])
        elif label and 'm_TreasureSubid' in s:
            tables[label] += 1
    return [t if isinstance(t, int) else tables.get(t, 0) for t in top]


def table(name, values):
    rows = [', '.join(str(v) for v in values[i:i + 16]) for i in range(0, len(values), 16)]
    return f'static const unsigned char {name}[] = {{\n  ' + ',\n  '.join(rows) + ',\n};\n'


with open(out, 'w') as f:
    f.write('// generated by tools/gen_treasures.py; do not edit\n#include "mods/treasures.h"\n\n')
    f.write(table('ages', counts('ages')) + '\n' + table('seasons', counts('seasons')) + '\n')
    f.write('int mods_treasure_subids(bool seasons_game, int id) {\n'
            '  const unsigned char *t = seasons_game ? seasons : ages;\n'
            '  int n = seasons_game ? (int)sizeof seasons : (int)sizeof ages;\n'
            '  return id >= 0 && id < n ? t[id] : 0;\n'
            '}\n\n'
            'bool mods_treasure_valid(bool seasons_game, int id, int subid) {\n'
            '  return subid >= 0 && subid < mods_treasure_subids(seasons_game, id);\n'
            '}\n')
